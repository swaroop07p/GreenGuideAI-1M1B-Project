import React, { useState } from 'react';
import { Calendar, CheckSquare, Square, Award, Clock, Sparkles, CheckCircle2 } from 'lucide-react';
import { useApp } from '../../context/AppContext';
import { formatCo2Value } from '../../utils/calculations';

export default function ActionPlan({ actionPlan }) {
  const { unit } = useApp();
  const [completedSteps, setCompletedSteps] = useState({});

  const planItems = actionPlan || [];
  if (planItems.length === 0) return null;

  // Calculate total steps and completed count
  let totalSteps = 0;
  planItems.forEach((w) => {
    totalSteps += (w.action_steps || []).length;
  });
  const completedCount = Object.values(completedSteps).filter(Boolean).length;
  const progressPercent = totalSteps > 0 ? Math.round((completedCount / totalSteps) * 100) : 0;

  const toggleStep = (weekIndex, stepIndex) => {
    const key = `${weekIndex}-${stepIndex}`;
    setCompletedSteps((prev) => ({
      ...prev,
      [key]: !prev[key]
    }));
  };

  // Clean any leading markdown bullets if generated by LLM
  const cleanStepText = (text) => {
    if (!text) return '';
    return text.replace(/^[-*•\d+.)\s]+/, '').trim();
  };

  return (
    <div className="rounded-3xl p-4 sm:p-8 bg-white dark:bg-zinc-900 border border-zinc-200/80 dark:border-zinc-800 shadow-sm transition-all">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 mb-4 sm:mb-6">
        <div className="flex items-center gap-3">
          <div className="p-2.5 rounded-2xl bg-purple-100 dark:bg-purple-950/80 text-purple-600 dark:text-purple-400 shrink-0">
            <Calendar className="w-5 h-5" />
          </div>
          <div>
            <div className="flex flex-wrap items-center gap-2">
              <h3 className="text-sm sm:text-lg font-bold text-zinc-900 dark:text-zinc-100">
                4-Week Progressive Action Plan
              </h3>
              <span className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-[10px] font-semibold bg-purple-50 dark:bg-purple-950/60 text-purple-700 dark:text-purple-300 border border-purple-200 dark:border-purple-800 shadow-2xs">
                <span className="w-1.5 h-1.5 rounded-full bg-purple-500 animate-pulse" />
                AI-Personalized Roadmap
              </span>
            </div>
            <p className="text-[11px] sm:text-xs text-zinc-500 dark:text-zinc-400 mt-0.5">
              A manageable step-by-step roadmap tailored to your highest emission sectors: quick wins first, compounding into lasting habits
            </p>
          </div>
        </div>

        {/* Progress Pill */}
        {totalSteps > 0 && (
          <div className="flex items-center gap-2.5 px-3 py-1.5 rounded-xl bg-zinc-50 dark:bg-zinc-800/60 border border-zinc-200/80 dark:border-zinc-700/80 self-start sm:self-auto">
            <div className="text-right">
              <div className="text-[10px] font-semibold text-zinc-500 dark:text-zinc-400">
                Checklist Progress
              </div>
              <div className="text-xs font-bold text-emerald-600 dark:text-emerald-400 font-mono">
                {completedCount} of {totalSteps} done ({progressPercent}%)
              </div>
            </div>
            <div className="w-10 bg-zinc-200 dark:bg-zinc-700 h-2 rounded-full overflow-hidden">
              <div
                className="h-full bg-emerald-500 transition-all duration-300"
                style={{ width: `${progressPercent}%` }}
              />
            </div>
          </div>
        )}
      </div>

      {/* Timeline List */}
      <div className="space-y-4 sm:space-y-6 relative before:absolute before:inset-0 before:left-5 before:w-0.5 before:bg-zinc-200 dark:before:bg-zinc-800 before:hidden md:before:block">
        {planItems.map((weekItem, wIdx) => {
          return (
            <div key={weekItem.week || wIdx} className="relative md:pl-12">
              {/* Timeline marker icon on desktop */}
              <div className="hidden md:flex absolute left-2 top-1.5 -translate-x-1/2 w-7 h-7 rounded-full bg-emerald-600 text-white items-center justify-center font-bold text-xs shadow-md">
                {weekItem.week}
              </div>

              <div className="p-3.5 sm:p-5 rounded-2xl border border-zinc-200/80 dark:border-zinc-800 bg-zinc-50/50 dark:bg-zinc-800/30 hover:border-emerald-500/40 transition-all">
                <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 mb-2">
                  <div className="flex items-center gap-2">
                    <span className="md:hidden px-2 py-0.5 rounded-md bg-emerald-600 text-white text-xs font-bold">
                      Week {weekItem.week}
                    </span>
                    <h4 className="text-sm sm:text-base font-bold text-zinc-900 dark:text-zinc-100">
                      {weekItem.title}
                    </h4>
                  </div>

                  <span className="text-xs font-bold text-emerald-600 dark:text-emerald-400 bg-emerald-50 dark:bg-emerald-950/60 px-2.5 py-1 rounded-full border border-emerald-200 dark:border-emerald-800 self-start sm:self-auto font-mono">
                    ~{formatCo2Value(weekItem.expected_impact_kg_monthly, unit)} / mo reduction
                  </span>
                </div>

                <p className="text-xs font-semibold text-emerald-800 dark:text-emerald-300 mb-3 bg-emerald-50/60 dark:bg-emerald-950/30 px-3 py-1.5 rounded-xl border border-emerald-200/60 dark:border-emerald-800/60 inline-block">
                  🎯 Focus Goal: {weekItem.focus_goal}
                </p>

                {/* Checklist Action Items */}
                <div className="space-y-2 pt-2 border-t border-zinc-200/60 dark:border-zinc-700/60">
                  {(weekItem.action_steps || []).map((step, sIdx) => {
                    const isDone = !!completedSteps[`${wIdx}-${sIdx}`];
                    return (
                      <div
                        key={sIdx}
                        onClick={() => toggleStep(wIdx, sIdx)}
                        className={`flex items-start gap-2.5 p-2 rounded-xl text-xs cursor-pointer transition-colors ${
                          isDone
                            ? 'bg-emerald-50/90 dark:bg-emerald-950/40 text-emerald-800 dark:text-emerald-300 line-through opacity-80'
                            : 'hover:bg-zinc-100 dark:hover:bg-zinc-700/40 text-zinc-700 dark:text-zinc-300'
                        }`}
                      >
                        {isDone ? (
                          <CheckSquare className="w-4 h-4 text-emerald-600 dark:text-emerald-400 shrink-0 mt-0.5" />
                        ) : (
                          <Square className="w-4 h-4 text-zinc-400 shrink-0 mt-0.5" />
                        )}
                        <span className="leading-relaxed">{cleanStepText(step)}</span>
                      </div>
                    );
                  })}
                </div>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
}
